proc bytes(values: openArray[byte]): string =
  result = newString(values.len)
  for i, value in values:
    result[i] = char(value)

# These bitstreams and expected values are derived from meshoptimizer's MIT
# licensed decoder tests.
echo "Testing EXT_meshopt_compression attribute mode."
let attributeData = bytes(@[
  0xa0'u8, 0x00, 0x01, 0x2a, 0xaa, 0xaa, 0xaa, 0x02,
  0x04, 0x44, 0x44, 0x44, 0x44, 0x44, 0x44, 0x44,
  0x03, 0x00, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10,
  0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10,
  0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00
])
var expectedAttributes = newString(16 * 4)
for i in 0 ..< 16:
  expectedAttributes[i * 4 + 0] = char(0)
  expectedAttributes[i * 4 + 1] = char(i)
  expectedAttributes[i * 4 + 2] = char(i * 2)
  expectedAttributes[i * 4 + 3] = char(i * 8)
doAssert decodeMeshopt(attributeData, 16, 4, "ATTRIBUTES", "NONE") ==
  expectedAttributes

